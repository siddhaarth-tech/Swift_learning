// Single-line string
let city = "Tokyo"
print(city)

// Multiline string
let note = """
Good Morning
Have a nice day
"""
print(note)

// Double quotes
let quote = "He said \"Hello\""
print(quote)

// Backslash
let path = "C:\\Users\\Alex"
print(path)

// New line
let lines = "One\nTwo"
print(lines)

// Tab
let table = "Name\tAge"
print(table)

// Carriage return
let word = "Apple\rOrange"
print(word)

// Unicode
let heart = "\u{2764}"
print(heart)

// Extended string delimiter
let text1 = #"One\nTwo"#
print(text1)

// Extended delimiter with escape
let text2 = #"One\#nTwo"#
print(text2)

// Multiline with """
let marks = #"""
Triple quotes: """
"""#
print(marks)
